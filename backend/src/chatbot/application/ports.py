from collections.abc import AsyncIterator, Sequence
from typing import Literal, Protocol
from uuid import UUID

from chatbot.domain.agent import AgentEvent, AgentRequest, ChatHistory, ModelEvent, ModelItem, ModelRequest
from chatbot.domain.models import Message, Turn, UserProfile
from chatbot.domain.auth import Account, AuthSession


class PasswordHasher(Protocol):
    async def hash(self, password: str) -> str: ...
    async def verify(self, encoded: str, password: str) -> bool: ...


class AuthRepository(Protocol):
    async def account(self, username: str) -> Account | None: ...
    async def create(self, account: Account, session: AuthSession | None, verifier: str | None, previous: str | None) -> None: ...
    async def login(self, session: AuthSession, verifier: str, previous: str | None) -> None: ...
    async def resolve(self, verifier: str) -> AuthSession | None: ...
    async def active(self, session_id: UUID, user_id: UUID) -> bool: ...
    async def revoke(self, verifier: str) -> None: ...
    async def list_accounts(self, actor_id: UUID, offset: int, limit: int) -> list[dict]: ...
    async def set_blocked(self, actor_id: UUID, user_id: UUID, blocked: bool) -> None: ...


class AuthLimiter(Protocol):
    def check(self, keys: list[tuple[str, int]]) -> None: ...


class ConversationRepository(Protocol):
    async def ready(self) -> None: ...
    async def profile(self, user_id: UUID) -> UserProfile | None: ...
    async def messages(self, user_id: UUID) -> list[Message]: ...
    async def begin(self, user_id: UUID, text: str) -> tuple[Turn, ChatHistory]: ...
    async def complete(
        self, turn: Turn, text: str, *, transcript: Sequence[ModelItem] = (), metadata: dict | None = None
    ) -> Message: ...
    async def finish(
        self, turn: Turn, status: Literal["failed", "cancelled"], code: str, *, metadata: dict | None = None
    ) -> None: ...


class AgentRunner(Protocol):
    provider: str
    model_name: str
    prompt_revision: str

    def stream(self, request: AgentRequest) -> AsyncIterator[AgentEvent]: ...


class ChatModel(Protocol):
    provider: str
    name: str

    def stream(self, request: ModelRequest) -> AsyncIterator[ModelEvent]: ...
    async def close(self) -> None: ...


class LockLease(Protocol):
    async def check(self) -> None: ...
    async def release(self) -> None: ...


class ConversationLock(Protocol):
    async def acquire(self, user_id: UUID) -> LockLease: ...


class IdentityProvider(Protocol):
    async def resolve(self, credential: str | None) -> UserProfile: ...


class RateLimiter(Protocol):
    def check(self, user_id: UUID) -> None: ...
